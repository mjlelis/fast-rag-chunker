# CJK sentence terminators in UTF-8 bytes:
# 。 = \xe3\x80\x82
# ！ = \xef\xbc\x81
# ？ = \xef\xbc\x9f
# ． = \xef\xbc\x8e
# … = \xe2\x80\xa6
# ‥ = \xe2\x80\xa5
CJK_PUNCTUATION_BYTES = [
    "。".encode("utf-8"),
    "！".encode("utf-8"),
    "？".encode("utf-8"),
    "．".encode("utf-8"),
    "…".encode("utf-8"),
    "‥".encode("utf-8"),
]


@dataclass(frozen=True)
class ChunkResult:
    """Represents a chunk generated by the chunking engine."""

    offset: int
    length: int
    digest: bytes
    hex: str
    ordinal: int = 0
    heading_path: list[str] = field(default_factory=list)
    context_before: str = ""
    context_after: str = ""

    def __post_init__(self) -> None:
        if len(self.digest) != 16:
            raise ValueError(f"Digest must be exactly 16 bytes, got {len(self.digest)}")
        if len(self.hex) != 32:
            raise ValueError(f"Hex string must be exactly 32 chars, got {len(self.hex)}")


class ChunkDiffResult(NamedTuple):
    """Categorized results from 3-way chunk diffing."""

    to_embed: list[ChunkResult]
    to_delete: list[ChunkResult]
    to_metadata_update: list[ChunkResult]


def resolve_snap_window(
    avg_chunk: int, min_chunk: int, max_chunk: int, user_snap: int | None
) -> int:
    """Resolves the dynamic or explicit snap window."""
    if user_snap is not None:
        return user_snap
    target = round(avg_chunk * 0.15)
    max_allowed = max(32, (max_chunk - min_chunk) // 2)
    return max(32, min(target, max_allowed))


@dataclass
class ChunkerConfig:
    """Configuration options for chunking."""

    min_chunk: int = 64
    max_chunk: int = 512
    avg_chunk: int | None = None
    mode: str = "boundary"
    compute_hash: bool = True
    snap_window: int | None = None
    size_unit: str = "bytes"
    normalize: str = "none"
    context_before: int = 0
    context_after: int = 0
    num_threads: int | None = None

    def __init__(
        self,
        min_chunk: int = 64,
        max_chunk: int = 512,
        avg_chunk: int | None = None,
        mode: str = "boundary",
        compute_hash: bool = True,
        snap_window: int | None = None,
        size_unit: str = "bytes",
        normalize: str = "none",
        context_before: int = 0,
        context_after: int = 0,
        num_threads: int | None = None,
        semantic_snap: bool | None = None,
        **kwargs,
    ) -> None:
        if "mask" in kwargs:
            raise TypeError("ChunkerConfig.__init__() got an unexpected keyword argument 'mask'")
        if kwargs:
            unexpected = next(iter(kwargs))
            raise TypeError(f"ChunkerConfig.__init__() got an unexpected keyword argument '{unexpected}'")

        if min_chunk <= 0:
            raise ValueError("Minimum chunk size must be greater than 0")
        if min_chunk > max_chunk:
            raise ValueError("Minimum chunk size cannot be greater than maximum")
        if max_chunk > MAX_CHUNK_SIZE_LIMIT:
            raise ValueError(f"Maximum chunk size exceeds maximum supported limit ({MAX_CHUNK_SIZE_LIMIT})")

        resolved_avg = avg_chunk if avg_chunk is not None else min_chunk + (max_chunk - min_chunk) // 2
        if resolved_avg < min_chunk or resolved_avg > max_chunk:
            raise ValueError(
                f"Average chunk size ({resolved_avg}) must be between minimum ({min_chunk}) and maximum ({max_chunk})"
            )

        if semantic_snap is not None:
            warnings.warn(
                "semantic_snap is deprecated since v0.3.0. Use mode='boundary' or mode='raw' instead.",
                DeprecationWarning,
                stacklevel=2,
            )
            mode = "boundary" if semantic_snap else "raw"

        norm_mode = mode.strip().lower()
        if norm_mode == "semantic":
            warnings.warn(
                "mode='semantic' is deprecated since v0.3.0 and will be removed in v1.0.0. Use mode='boundary' instead.",
                DeprecationWarning,
                stacklevel=2,
            )
            norm_mode = "boundary"

        valid_modes = {"boundary", "boundary_aware", "raw", "compat_c"}
        if norm_mode not in valid_modes:
            raise ValueError(f"Invalid mode: '{mode}'. Expected one of {sorted(valid_modes)}")

        if size_unit not in ("bytes", "tokens"):
            raise ValueError(f"Invalid size_unit: '{size_unit}'. Expected 'bytes' or 'tokens'")

        if normalize not in ("none", "whitespace", "nfc"):
            raise ValueError(f"Invalid normalize: '{normalize}'. Expected 'none', 'whitespace', or 'nfc'")

        if num_threads is not None and num_threads <= 0:
            raise ValueError("Invalid thread count (0): num_threads must be >= 1")

        self.min_chunk = min_chunk
        self.max_chunk = max_chunk
        self.avg_chunk = resolved_avg
        self.mode = norm_mode
        self.compute_hash = compute_hash
        self.snap_window = snap_window
        self.size_unit = size_unit
        self.normalize = normalize
        self.context_before = context_before
        self.context_after = context_after
        self.num_threads = num_threads

    def fingerprint(self) -> str:
        """Returns the configuration fingerprint string."""
        spec = (
            f"{ALGORITHM_VERSION}:{self.min_chunk}:{self.avg_chunk}:{self.max_chunk}:"
            f"{self.mode}:{self.compute_hash}:{self.snap_window}:{self.size_unit}:"
            f"{self.normalize}:{self.context_before}:{self.context_after}"
        )
        hasher = blake3.blake3(spec.encode("utf-8"))
        return hasher.hexdigest()[:32]


def chunker_fingerprint(
    config: ChunkerConfig | None = None,
    *,
    min_chunk: int = 64,
    avg_chunk: int | None = None,
    max_chunk: int = 512,
    mode: str = "boundary",
    compute_hash: bool = True,
    snap_window: int | None = None,
    size_unit: str = "bytes",
    normalize: str = "none",
    context_before: int = 0,
    context_after: int = 0,
) -> str:
    """Calculates the configuration fingerprint."""
    if config is not None:
        return config.fingerprint()
    cfg = ChunkerConfig(
        min_chunk=min_chunk,
        avg_chunk=avg_chunk,
        max_chunk=max_chunk,
        mode=mode,
        compute_hash=compute_hash,
        snap_window=snap_window,
        size_unit=size_unit,
        normalize=normalize,
        context_before=context_before,
        context_after=context_after,
    )
    return cfg.fingerprint()


def cache_key(
    chunk: ChunkResult,
    model_id: str,
    config: ChunkerConfig | None = None,
    *,
    min_chunk: int = 64,
    avg_chunk: int | None = None,
    max_chunk: int = 512,
    mode: str = "boundary",
    compute_hash: bool = True,
    with_context: bool = False,
) -> str:
    """Builds a collision-resistant embedding cache key."""
    if chunk.digest == b"\x00" * 16:
        raise ValueError("Cannot generate a cache key for a chunk with an empty (all-zero) digest")
    if config is not None and not config.compute_hash:
        raise ValueError("Cannot generate cache key when compute_hash is disabled")

    fp = chunker_fingerprint(
        config=config,
        min_chunk=min_chunk,
        avg_chunk=avg_chunk,
        max_chunk=max_chunk,
        mode=mode,
        compute_hash=compute_hash,
    )

    if not with_context:
        payload = f"{ALGORITHM_VERSION}:{model_id}:{fp}:{chunk.hex}"
    else:
        payload = (
            f"{ALGORITHM_VERSION}:{model_id}:{fp}:{chunk.hex}:"
            f"{chunk.context_before}:{chunk.context_after}"
        )
    key_hash = blake3.blake3(payload.encode("utf-8")).hexdigest()[:32]
    return f"frc:v0.3.0:{key_hash}"


def _normalize_slice(raw_bytes: bytes, mode: str) -> bytes:
    """Applies pre-hash normalization without altering original byte offsets."""
    if mode == "none":
        return raw_bytes
    text = raw_bytes.decode("utf-8", errors="replace")
    if mode == "whitespace":
        text = text.replace("\r\n", "\n").replace("\r", "\n")
        text = re.sub(r"[ \t]+", " ", text)
        text = text.strip()
        return text.encode("utf-8")
    if mode == "nfc":
        text = unicodedata.normalize("NFC", text)
        text = text.replace("\r\n", "\n").replace("\r", "\n")
        text = re.sub(r"\s+", " ", text).strip()
        return text.encode("utf-8")
    return raw_bytes


def _compute_chunk_digest(raw_slice: bytes, compute_hash: bool, normalize_mode: str) -> tuple[bytes, str]:
    """Computes the 128-bit truncated BLAKE3 digest and hex string."""
    if not compute_hash:
        return b"\x00" * 16, "0" * 32
    target_bytes = _normalize_slice(raw_slice, normalize_mode)
    hasher = blake3.blake3(target_bytes)
    digest = hasher.digest()[:16]
    return digest, digest.hex()


def _is_sentence_abbreviation(data: bytes, period_byte_idx: int) -> bool:
    """Checks if a period byte belongs to a known abbreviation."""
    # Find word preceding period
    start = period_byte_idx - 1
    while start >= 0 and (data[start : start + 1].isalnum() or data[start : start + 1] in b".-"):
        start -= 1
    word_bytes = data[start + 1 : period_byte_idx]
    try:
        word = word_bytes.decode("utf-8").lower().strip(".")
        return word in ALL_ABBREVIATIONS
    except UnicodeDecodeError:
        return False


def _find_priority_boundary(data: bytes, window_start: int, window_end: int) -> int | None:
    """Finds the highest priority byte boundary in data[window_start:window_end]."""
    if window_start >= window_end:
        return None

    span = data[window_start:window_end]

    # Priority 1: Markdown Heading (\n#{1,6}\s+ or ^#{1,6}\s+)
    heading_matches = list(re.finditer(rb"(?:^|\n)(#{1,6}[ \t]+[^\n]+)", span))
    if heading_matches:
        m = heading_matches[0]
        cut = window_start + m.start()
        if m.start() > 0 and span[m.start() : m.start() + 1] == b"\n":
            cut += 1  # Cut point is immediately before #
        return cut

    # Priority 2: Blank line / Paragraph (\n[\t ]*\r?\n)
    para_matches = list(re.finditer(rb"\n[ \t]*\r?\n", span))
    if para_matches:
        m = para_matches[0]
        return window_start + m.end()

    # Priority 3: Sentence boundary
    # First check CJK punctuation sequences
    for cjk_seq in CJK_PUNCTUATION_BYTES:
        idx = span.find(cjk_seq)
        if idx != -1:
            return window_start + idx + len(cjk_seq)

    # Next check Latin sentence terminators (. ! ?)
    for i in range(len(span)):
        b = span[i : i + 1]
        if b in b".!?":
            global_idx = window_start + i
            if not _is_sentence_abbreviation(data, global_idx):
                cut = global_idx + 1
                while cut < len(data) and data[cut : cut + 1] in b" \t":
                    cut += 1
                return cut

    # Priority 4: Word boundary (Unicode whitespace in UTF-8)
    for i in range(len(span) - 1, -1, -1):
        if span[i : i + 1] in b" \t\r\n":
            return window_start + i + 1

    return None


def _extract_sentences(text: str) -> list[tuple[int, int, str]]:
    """Segments text into sentences with start and end indices."""
    sentences: list[tuple[int, int, str]] = []
    current_start = 0
    i = 0
    data = text.encode("utf-8")
    while i < len(text):
        ch = text[i]
        is_cjk_term = ch in ("。", "！", "？", "．", "…", "‥", "；", "：")
        is_latin_term = ch in ".!?"
        if is_latin_term:
            # check abbreviation
            byte_idx = len(text[:i].encode("utf-8"))
            if _is_sentence_abbreviation(data, byte_idx):
                is_latin_term = False

        if is_cjk_term or is_latin_term:
            end_idx = i + 1
            while end_idx < len(text) and text[end_idx] in " \t\r\n":
                end_idx += 1
            sent_str = text[current_start:end_idx].strip()
            if sent_str:
                sentences.append((current_start, end_idx, sent_str))
            current_start = end_idx
            i = end_idx
        else:
            i += 1
    if current_start < len(text):
        sent_str = text[current_start:].strip()
        if sent_str:
            sentences.append((current_start, len(text), sent_str))
    return sentences


def _extract_heading_stack_at(data: bytes, chunk_offset: int, chunk_length: int) -> list[str]:
    """Builds the active hierarchical heading stack for a chunk at chunk_offset."""
    # Scan all headings up to the end of the current chunk
    prefix_bytes = data[: chunk_offset + chunk_length]
    prefix_text = prefix_bytes.decode("utf-8", errors="replace")
    lines = prefix_text.splitlines()

    stack: list[tuple[int, str]] = []

    for line in lines:
        m = re.match(r"^(#{1,6})\s+(.+)$", line.strip())
        if m:
            level = len(m.group(1))
            title = m.group(2).strip()
            while stack and stack[-1][0] >= level:
                stack.pop()
            stack.append((level, title))

    return [t for _, t in stack]


def _chunk_single_document(doc: bytes, config: ChunkerConfig) -> list[ChunkResult]:
    """Chunks a single byte document according to the configuration."""
    if not doc:
        return []

    doc_len = len(doc)
    doc_text = doc.decode("utf-8", errors="replace")

    # Determine token spans if size_unit == "tokens"
    is_tokens = config.size_unit == "tokens"
    token_spans: list[tuple[int, int]] = []
    if is_tokens:
        for m in re.finditer(r"\S+", doc_text):
            token_spans.append((m.start(), m.end()))
        if not token_spans:
            return []
        if len(token_spans) <= config.max_chunk:
            digest, hex_str = _compute_chunk_digest(doc, config.compute_hash, config.normalize)
            h_path = _extract_heading_stack_at(doc, 0, doc_len)
            return [
                ChunkResult(
                    offset=0,
                    length=doc_len,
                    digest=digest,
                    hex=hex_str,
                    ordinal=0,
                    heading_path=h_path,
                )
            ]

    min_limit = config.min_chunk
    max_limit = config.max_chunk
    avg_limit = config.avg_chunk or (min_limit + (max_limit - min_limit) // 2)

    chunks: list[ChunkResult] = []
    sentences = _extract_sentences(doc_text)
    snap_win = resolve_snap_window(avg_limit, min_limit, max_limit, config.snap_window)

    offset = 0
    ordinal = 0

    while offset < doc_len:
        remaining = doc_len - offset

        # Tail remainder handling (< min_limit)
        if remaining < min_limit:
            if not chunks:
                # Document smaller than min_chunk is emitted as a single chunk
                digest, hex_str = _compute_chunk_digest(doc[offset:], config.compute_hash, config.normalize)
                h_path = _extract_heading_stack_at(doc, offset, remaining)
                chunks.append(
                    ChunkResult(
                        offset=offset,
                        length=remaining,
                        digest=digest,
                        hex=hex_str,
                        ordinal=ordinal,
                        heading_path=h_path,
                    )
                )
                break

            prev_chunk = chunks[-1]
            combined_len = prev_chunk.length + remaining

            if combined_len <= max_limit:
                # Merge into previous chunk
                new_len = combined_len
                merged_slice = doc[prev_chunk.offset : prev_chunk.offset + new_len]
                digest, hex_str = _compute_chunk_digest(merged_slice, config.compute_hash, config.normalize)
                chunks[-1] = ChunkResult(
                    offset=prev_chunk.offset,
                    length=new_len,
                    digest=digest,
                    hex=hex_str,
                    ordinal=prev_chunk.ordinal,
                    heading_path=prev_chunk.heading_path,
                    context_before=prev_chunk.context_before,
                    context_after=prev_chunk.context_after,
                )
                break
            else:
                # Balanced midpoint redistribution
                midpoint = prev_chunk.offset + combined_len // 2
                split_start = max(prev_chunk.offset + min_limit, midpoint - snap_win)
                split_end = min(prev_chunk.offset + combined_len - min_limit, midpoint + snap_win)
                bound = None
                if config.mode in ("boundary", "boundary_aware"):
                    bound = _find_priority_boundary(doc, split_start, split_end)
                if bound is None:
                    bound = midpoint

                first_len = bound - prev_chunk.offset
                second_len = combined_len - first_len

                d1, h1 = _compute_chunk_digest(
                    doc[prev_chunk.offset : bound], config.compute_hash, config.normalize
                )
                chunks[-1] = ChunkResult(
                    offset=prev_chunk.offset,
                    length=first_len,
                    digest=d1,
                    hex=h1,
                    ordinal=prev_chunk.ordinal,
                    heading_path=prev_chunk.heading_path,
                )

                d2, h2 = _compute_chunk_digest(doc[bound : bound + second_len], config.compute_hash, config.normalize)
                h_path2 = _extract_heading_stack_at(doc, bound, second_len)
                chunks.append(
                    ChunkResult(
                        offset=bound,
                        length=second_len,
                        digest=d2,
                        hex=h2,
                        ordinal=prev_chunk.ordinal + 1,
                        heading_path=h_path2,
                    )
                )
                break

        # Sizing target
        target_cut = min(offset + avg_limit, doc_len)
        cut_point = min(offset + max_limit, doc_len)

        if config.mode in ("boundary", "boundary_aware"):
            w_start = max(offset + min_limit, target_cut - snap_win)
            w_end = min(offset + max_limit, target_cut + snap_win)
            chosen_boundary = _find_priority_boundary(doc, w_start, w_end)
            if chosen_boundary is not None and chosen_boundary > offset:
                cut_point = chosen_boundary
            else:
                cut_point = min(offset + avg_limit, offset + max_limit)
        elif config.mode == "raw":
            cut_point = min(offset + avg_limit, offset + max_limit)
        else:
            cut_point = min(offset + avg_limit, offset + max_limit)

        # Enforce UTF-8 codepoint boundary fallback
        while cut_point < doc_len and (doc[cut_point] & 0xC0) == 0x80:
            cut_point += 1

        length = min(cut_point - offset, doc_len - offset)
        if length <= 0:
            length = min(remaining, max_limit)

        # Token hard upper-bound check
        if is_tokens:
            chunk_text = doc[offset : offset + length].decode("utf-8", errors="replace")
            tok_count = len(re.findall(r"\S+", chunk_text))
            if tok_count > max_limit:
                tok_matches = list(re.finditer(r"\S+", chunk_text))
                if tok_matches and len(tok_matches) > max_limit:
                    last_tok = tok_matches[max_limit - 1]
                    length = last_tok.end()

        raw_slice = doc[offset : offset + length]
        digest, hex_str = _compute_chunk_digest(raw_slice, config.compute_hash, config.normalize)
        h_path = _extract_heading_stack_at(doc, offset, length)

        chunks.append(
            ChunkResult(
                offset=offset,
                length=length,
                digest=digest,
                hex=hex_str,
                ordinal=ordinal,
                heading_path=h_path,
            )
        )
        offset += length
        ordinal += 1

    # Extract context windowing if configured
    if config.context_before > 0 or config.context_after > 0:
        for idx, c in enumerate(chunks):
            ctx_before_list: list[str] = []
            ctx_after_list: list[str] = []

            # Find character offset of c.offset and c.offset + c.length
            c_char_start = len(doc[: c.offset].decode("utf-8", errors="replace"))
            c_char_end = len(doc[: c.offset + c.length].decode("utf-8", errors="replace"))

            if config.context_before > 0:
                for s_start, s_end, s_text in reversed(sentences):
                    if s_end <= c_char_start:
                        ctx_before_list.append(s_text)
                        if len(ctx_before_list) >= config.context_before:
                            break
                ctx_before_list.reverse()

            if config.context_after > 0:
                for s_start, s_end, s_text in sentences:
                    if s_start >= c_char_end:
                        ctx_after_list.append(s_text)
                        if len(ctx_after_list) >= config.context_after:
                            break

            chunks[idx] = ChunkResult(
                offset=c.offset,
                length=c.length,
                digest=c.digest,
                hex=c.hex,
                ordinal=c.ordinal,
                heading_path=c.heading_path,
                context_before=" ".join(ctx_before_list),
                context_after=" ".join(ctx_after_list),
            )

    return chunks


def chunk_documents_batch(
    documents: Sequence[bytes],
    min_chunk: int = 64,
    max_chunk: int = 512,
    avg_chunk: int | None = None,
    mode: str = "boundary",
    compute_hash: bool = True,
    num_threads: int | None = None,
    *,
    snap_window: int | None = None,
    size_unit: str = "bytes",
    normalize: str = "none",
    context_before: int = 0,
    context_after: int = 0,
    semantic_snap: bool | None = None,
    config: ChunkerConfig | None = None,
    **kwargs,
) -> list[list[ChunkResult]]:
    """Chunks a batch of byte documents."""
    if config is None:
        cfg = ChunkerConfig(
            min_chunk=min_chunk,
            max_chunk=max_chunk,
            avg_chunk=avg_chunk,
            mode=mode,
            compute_hash=compute_hash,
            snap_window=snap_window,
            size_unit=size_unit,
            normalize=normalize,
            context_before=context_before,
            context_after=context_after,
            num_threads=num_threads,
            semantic_snap=semantic_snap,
            **kwargs,
        )
    else:
        cfg = config
        if num_threads is not None:
            if num_threads <= 0:
                raise ValueError("Invalid thread count (0): num_threads must be >= 1")
            cfg.num_threads = num_threads

    return [_chunk_single_document(doc, cfg) for doc in documents]


def diff_chunks(
    old_chunks: list[ChunkResult], new_chunks: list[ChunkResult]
) -> ChunkDiffResult:
    """Computes the 3-way incremental chunk diff."""
    old_by_digest: dict[bytes, list[ChunkResult]] = {}
    for c in old_chunks:
        old_by_digest.setdefault(c.digest, []).append(c)

    new_by_digest: dict[bytes, list[ChunkResult]] = {}
    for c in new_chunks:
        new_by_digest.setdefault(c.digest, []).append(c)

    to_embed: list[ChunkResult] = []
    to_delete: list[ChunkResult] = []
    to_metadata_update: list[ChunkResult] = []

    for c in new_chunks:
        if c.digest not in old_by_digest:
            to_embed.append(c)
        else:
            matches = old_by_digest[c.digest]
            identical_metadata = any(
                m.ordinal == c.ordinal
                and m.heading_path == c.heading_path
                and m.offset == c.offset
                for m in matches
            )
            if not identical_metadata:
                to_metadata_update.append(c)

    for c in old_chunks:
        if c.digest not in new_by_digest:
            to_delete.append(c)

    return ChunkDiffResult(
        to_embed=to_embed,
        to_delete=to_delete,
        to_metadata_update=to_metadata_update,
    )
